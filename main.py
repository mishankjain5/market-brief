import os
import requests
from datetime import datetime
from groq import Groq
import pytz

# ── API Keys (loaded from environment / GitHub Secrets) ──────────────────────
GROQ_API_KEY        = os.environ["GROQ_API_KEY"]
TAVILY_API_KEY      = os.environ["TAVILY_API_KEY"]
TELEGRAM_BOT_TOKEN  = os.environ["TELEGRAM_BOT_TOKEN"]
TELEGRAM_CHANNEL_ID = os.environ["TELEGRAM_CHANNEL_ID"]      # e.g. @YourChannelName or -100xxxxxxxxxx
CALLMEBOT_PHONE     = os.environ.get("CALLMEBOT_PHONE", "")  # optional: +91XXXXXXXXXX
CALLMEBOT_APIKEY    = os.environ.get("CALLMEBOT_APIKEY", "")  # optional

# ── Step 1: Search latest market news via Tavily ─────────────────────────────
def search_market_news():
    queries = [
        "India NSE Nifty 50 Sensex stock market today",
        "US S&P 500 NASDAQ Dow Jones stock market today",
        "European stocks FTSE 100 DAX CAC 40 today",
        "China Shanghai Composite Hang Seng today",
        "Japan Nikkei 225 South Korea KOSPI today",
        "crude oil Brent WTI gold silver commodities price today",
        "tech stocks AI semiconductor big tech news today",
        "Fed RBI ECB central bank economic data macro news today",
    ]
    all_results = []
    for query in queries:
        resp = requests.post(
            "https://api.tavily.com/search",
            json={
                "api_key": TAVILY_API_KEY,
                "query": query,
                "search_depth": "advanced",
                "max_results": 3,
                "include_published_date": True,
            },
            timeout=15,
        )
        if resp.status_code == 200:
            all_results.extend(resp.json().get("results", []))
    return all_results


def build_context(results):
    ctx = ""
    for r in results:
        ctx += (
            f"\nTitle: {r.get('title','')}"
            f"\nURL: {r.get('url','')}"
            f"\nDate: {r.get('published_date','N/A')}"
            f"\nContent: {r.get('content','')[:600]}"
            f"\n{'─'*60}"
        )
    return ctx


