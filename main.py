# ── Step 3: Deliver to Telegram ───────────────────────────────────────────────
def send_telegram(brief):
    max_len = 4096
    # Split on paragraph boundaries to keep formatting intact
    parts = []
    while len(brief) > max_len:
        split_at = brief.rfind("\n", 0, max_len)
        if split_at == -1:
            split_at = max_len
        parts.append(brief[:split_at])
        brief = brief[split_at:].lstrip()
    parts.append(brief)

    for i, part in enumerate(parts):
        resp = requests.post(
            f"https://api.telegram.org/bot{TELEGRAM_BOT_TOKEN}/sendMessage",
            json={
                "chat_id": TELEGRAM_CHANNEL_ID,
                "text": part,
                "parse_mode": "Markdown",
                "disable_web_page_preview": True,
            },
            timeout=15,
        )
        if resp.status_code != 200:
            print(f"Telegram error on part {i+1}: {resp.text}")
    print(f"✅ Sent {len(parts)} Telegram message(s).")


# ── Step 4: Deliver to WhatsApp via CallMeBot (free, personal) ───────────────
def send_whatsapp(brief):
    if not (CALLMEBOT_PHONE and CALLMEBOT_APIKEY):
        return
    # WhatsApp / CallMeBot has a shorter limit — send a condensed version
    summary = brief[:1500] + "\n\n📲 Full report on our Telegram channel!"
    encoded = requests.utils.quote(summary)
    url = (
        f"https://api.callmebot.com/whatsapp.php"
        f"?phone={CALLMEBOT_PHONE}&text={encoded}&apikey={CALLMEBOT_APIKEY}"
    )
    resp = requests.get(url, timeout=15)
    if resp.status_code == 200:
        print("✅ WhatsApp notification sent.")
    else:
        print(f"WhatsApp error: {resp.text}")


# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    ist = pytz.timezone("Asia/Kolkata")
    date_str = datetime.now(ist).strftime("%B %d, %Y")
    print(f"\n📰 Generating Market Brief for {date_str} ...\n")

    print("🔍 Searching latest market news...")
    results = search_market_news()
    context = build_context(results)
    print(f"   Found {len(results)} articles.\n")

    print("🤖 Generating AI brief with Groq (Llama 3.3 70B)...")
    brief = generate_brief(date_str, context)
    print("   Brief generated.\n")

    print("📤 Sending to Telegram...")
    send_telegram(brief)

    print("📱 Sending WhatsApp notification...")
    send_whatsapp(brief)

    print("\n🎉 All done!")


if __name__ == "__main__":
    main()
